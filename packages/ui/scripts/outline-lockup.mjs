// Outlines the lockup words from Martian Mono (wght 380, wdth 112.5) into SVG
// path data, so the font itself never ships. Run once when the wordmark
// changes, not in CI:
//   npm i --no-save fontkit@2
//   curl -L -o martian.ttf "https://github.com/google/fonts/raw/main/ofl/martianmono/MartianMono%5Bwdth,wght%5D.ttf"
//   node scripts/outline-lockup.mjs martian.ttf > src/lockup/glyphs.ts
// Units: the lockup is drawn with c = 100 (c is the lockup height / 1.51),
// so the font size is 130, letter spacing 0.03em and the baseline sits at
// 127.5, matching the Doop snippet's line-height 1 box centred in 151.
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const fontkit = require("fontkit")

const fontSize = 130
const baseline = 127.5
const letterSpacing = 0.03 * fontSize
const words = ["MATCHBOX", "MATCH", "PRO", "SCAN", "ID", "DEVELOPER", "CLASSIC"]

const font = fontkit
  .openSync(process.argv[2])
  .getVariation({ wght: 380, wdth: 112.5 })
const scale = fontSize / font.unitsPerEm
const round = (value) => Math.round(value * 100) / 100

function outline(word) {
  const run = font.layout(word)
  let x = 0
  const parts = []
  run.glyphs.forEach((glyph, index) => {
    const tx = (px) => round(x + px * scale)
    const ty = (py) => round(baseline - py * scale)
    for (const { command, args } of glyph.path.commands) {
      if (command === "moveTo") parts.push(`M${tx(args[0])} ${ty(args[1])}`)
      else if (command === "lineTo")
        parts.push(`L${tx(args[0])} ${ty(args[1])}`)
      else if (command === "quadraticCurveTo")
        parts.push(
          `Q${tx(args[0])} ${ty(args[1])} ${tx(args[2])} ${ty(args[3])}`,
        )
      else if (command === "bezierCurveTo")
        parts.push(
          `C${tx(args[0])} ${ty(args[1])} ${tx(args[2])} ${ty(args[3])} ${tx(args[4])} ${ty(args[5])}`,
        )
      else if (command === "closePath") parts.push("Z")
    }
    x += run.positions[index].xAdvance * scale + letterSpacing
  })
  return { d: parts.join(""), width: round(x) }
}

const ch = round(font.layout("0").positions[0].xAdvance * scale)
const lines = [
  "// Generated by scripts/outline-lockup.mjs from Martian Mono (OFL), wght 380,",
  "// wdth 112.5. Do not edit by hand.",
  "",
  "export type LockupGlyph = { width: number; d: string }",
  "",
  "/** One monospace cell (1ch) at the lockup's font size. */",
  `export const lockupCh = ${ch}`,
]
// One export per word so bundlers keep only the words a product uses.
for (const word of words) {
  const { d, width } = outline(word)
  lines.push(
    "",
    `export const ${word}: LockupGlyph = {`,
    `  width: ${width},`,
    `  d: "${d}",`,
    "}",
  )
}
lines.push("")
process.stdout.write(lines.join("\n"))

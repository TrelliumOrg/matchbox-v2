/**
 * Every old docs URL and where it goes. Served as the site's `_redirects`
 * (Cloudflare static assets: no Worker runs) and tested against the built
 * pages: each old URL must land on a published page in at most two hops.
 *
 * Old URLs come from two places:
 * - matchdocs (Astro Starlight, `matchbox.markets/docs/<path>/`). A zone
 *   Single Redirect sends `matchbox.markets/docs*` to
 *   `docs.matchbox.markets/docs${1}`, and the rules below finish the move.
 *   Its short forms without `/docs` (`/guides/voting`, the broken relative
 *   links) arrive on this host directly.
 * - Classic's developer console (`developer.matchbox.markets/docs[/x]`),
 *   which the v2 console already answers with a 302 to
 *   `docs.matchbox.markets/developer[/x]` (apps/developer docs-redirect.ts).
 *   Those land on real pages with the same slugs; fragments such as
 *   `/developer/errors#rate_limited` keep their ids, and the reference
 *   page maps Classic's `#get-v1-…` anchors to operation pages in the
 *   browser, since fragments never reach a server.
 *
 * Every target carries `?from=matchdocs`. Before the cutover Netlify
 * answered every docs.matchbox.markets path with a 301 to
 * `matchbox.markets/docs<path>` and no Cache-Control, so a returning
 * browser may hold that 301 for any bare path here. A rule landing on a
 * bare path could send it back round the zone redirect forever. No
 * browser has a 301 cached for a URL with the marker, so every chain ends.
 * The page's canonical link drops it.
 */

/** On every redirect target, so no cached Classic 301 can catch it. */
export const redirectMarker = "from=matchdocs"

export type Redirect = { from: string; to: string; status: 301 | 302 }

/** matchdocs pages, by their path under /docs (no trailing slash). */
const matchdocsMoves: readonly (readonly [string, string])[] = [
  ["", "/"],
  ["/getting-started", "/pro"],
  ["/concepts", "/concepts"],
  ["/concepts/vebtc", "/concepts/vebtc"],
  ["/concepts/vemezo", "/concepts/vemezo"],
  ["/concepts/gauges", "/concepts/gauges"],
  ["/concepts/epochs", "/concepts/epochs"],
  ["/guides/voting", "/pro/vote"],
  ["/guides/managing-gauges", "/pro/incentives"],
  ["/guides/dashboard", "/pro/overview"],
  ["/reference/faq", "/pro/faq"],
  ["/reference/glossary", "/concepts/glossary"],
]

function variants(path: string): string[] {
  return path === "" ? [] : [path, `${path}/`]
}

function marked(rule: Redirect): Redirect {
  return { ...rule, to: `${rule.to}?${redirectMarker}` }
}

export const redirects: readonly Redirect[] = (
  [
    // matchdocs under /docs, with and without the trailing slash.
    { from: "/docs", to: "/", status: 301 },
    { from: "/docs/", to: "/", status: 301 },
    ...matchdocsMoves.flatMap(([old, to]) =>
      variants(old).map((path) => ({
        from: `/docs${path}`,
        to,
        status: 301 as const,
      })),
    ),
    // The short forms on this host. `/concepts/<x>` are real pages already.
    ...matchdocsMoves
      .filter(([old]) => old !== "" && !old.startsWith("/concepts"))
      .flatMap(([old, to]) =>
        variants(old).map((path) => ({ from: path, to, status: 301 as const })),
      ),
    // Starlight's assets and search index: nothing to serve.
    { from: "/_astro/*", to: "/", status: 301 },
    { from: "/pagefind/*", to: "/", status: 301 },
    // Any other old matchdocs path.
    { from: "/docs/*", to: "/", status: 301 },
  ] satisfies Redirect[]
).map(marked)


export function redirectsFile(): string {
  const width = Math.max(...redirects.map((rule) => rule.from.length))
  const lines = redirects.map(
    (rule) => `${rule.from.padEnd(width)}  ${rule.to}  ${rule.status}`,
  )
  return `# Generated by packages/docs (src/redirects.ts). Old docs URLs.\n${lines.join("\n")}\n`
}

/**
 * Cloudflare's `_redirects` matching, for tests: static rules before
 * splats, first match wins, `:splat` takes what `*` matched.
 */
export function matchRedirect(path: string): Redirect | null {
  const statics = redirects.filter((rule) => !rule.from.includes("*"))
  const dynamics = redirects.filter((rule) => rule.from.includes("*"))
  const exact = statics.find((rule) => rule.from === path)
  if (exact !== undefined) return exact
  for (const rule of dynamics) {
    const prefix = rule.from.slice(0, rule.from.indexOf("*"))
    if (path.startsWith(prefix)) {
      const splat = path.slice(prefix.length)
      return { ...rule, to: rule.to.replace(":splat", splat) }
    }
  }
  return null
}

export type Resolution =
  | { kind: "page"; path: string; hops: number }
  | { kind: "missing"; path: string; hops: number }

/**
 * Follows redirects and the host's trailing-slash rule (`/x/` to `/x`)
 * until a published page or a dead end, at most five hops.
 */
export function resolveUrl(
  url: string,
  pages: ReadonlySet<string>,
): Resolution {
  let path = url.split("#")[0]?.split("?")[0] ?? url
  let hops = 0
  for (let step = 0; step < 5; step += 1) {
    const rule = matchRedirect(path)
    if (rule !== null) {
      path = rule.to.split("?")[0] ?? rule.to
      hops += 1
      continue
    }
    if (pages.has(path)) return { kind: "page", path, hops }
    if (path.length > 1 && path.endsWith("/")) {
      path = path.slice(0, -1)
      hops += 1
      continue
    }
    return { kind: "missing", path, hops }
  }
  return { kind: "missing", path, hops }
}

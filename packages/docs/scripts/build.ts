import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { buildSite } from "../src/pipeline/build-site"
import { loadContent } from "../src/pipeline/content"
import { generatedFiles } from "../src/pipeline/emit"
import { generateMcpTools, readMcpTools } from "../src/pipeline/mcp-tools"
import {
  generateReference,
  referencePage,
  samplesModule,
} from "../src/pipeline/reference"
import { contractTables } from "../src/pipeline/tables"
import { redirectsFile } from "../src/redirects"
import { chunkName } from "../src/site"

/**
 * Builds the docs from packages/docs/content, packages/contracts/openapi.json
 * and the MCP tool schemas.
 *
 *   tsx scripts/build.ts                     dist/ for apps/docs
 *   tsx scripts/build.ts --write-generated   also rewrites src/*.gen.*
 *   tsx scripts/build.ts --check             fails if src/*.gen.* is stale
 *
 * Any copy, link, anchor or tree problem fails the build.
 */

const root = fileURLToPath(new URL("..", import.meta.url))
const dist = join(root, "dist")
const args = new Set(process.argv.slice(2))

function write(file: string, text: string): void {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
}

const content = loadContent(join(root, "content"))
const reference = await generateReference()
const mcp = await generateMcpTools(readMcpTools())

const output = await buildSite({
  content,
  generated: [referencePage(reference), ...reference.pages, ...mcp.pages],
  generatedTrees: [reference.tree, mcp.tree],
  tables: contractTables,
  apiVersion: reference.version,
  files: ["/developer/openapi.json", "/llms.txt", "/sitemap.xml"],
  generatedTreeOf: () => null,
})

if (output.problems.length > 0) {
  for (const problem of output.problems) console.error(problem)
  console.error(`\n${output.problems.length} docs problems`)
  // Local drafting only: CI never passes it.
  if (!args.has("--allow-problems")) process.exit(1)
}

const generated = await generatedFiles(output)
generated.set(
  "src/samples.gen.ts",
  samplesModule([...reference.samples, ...output.samples]),
)
let stale = 0
for (const [relative, text] of generated) {
  const file = join(root, relative)
  let current: string | null = null
  try {
    current = readFileSync(file, "utf8")
  } catch {
    current = null
  }
  if (current === text) continue
  if (args.has("--write-generated")) {
    write(file, text)
    console.log(`wrote ${relative}`)
  } else {
    stale += 1
    console.error(
      `${relative} is out of date: run pnpm --filter @matchbox/docs generate`,
    )
  }
}
if (stale > 0) process.exit(1)
if (args.has("--check")) {
  console.log("generated files are up to date")
  process.exit(0)
}

rmSync(dist, { recursive: true, force: true })

// One JSON chunk per page, and the module that imports them on demand.
const loaders: string[] = []
for (const [path, page] of output.pages) {
  const name = chunkName(path)
  write(join(dist, "pages", `${name}.json`), JSON.stringify(page))
  loaders.push(
    `  ${JSON.stringify(path)}: () => import("./pages/${name}.json"),`,
  )
}
write(
  join(dist, "pages.js"),
  `// Generated by packages/docs/scripts/build.ts.\nexport const pageLoaders = {\n${loaders.join("\n")}\n}\n`,
)
write(
  join(dist, "pages.d.ts"),
  `import type { PageData } from "../src/render-types"\nexport declare const pageLoaders: Readonly<Record<string, () => Promise<{ default: PageData }>>>\n`,
)
write(
  join(dist, "manifest.js"),
  `// Generated by packages/docs/scripts/build.ts.\nexport const manifest = ${JSON.stringify(output.manifest)}\n`,
)
write(
  join(dist, "manifest.d.ts"),
  `import type { Manifest } from "../src/manifest"\nexport type { Manifest, ManifestPage, ManifestTree } from "../src/manifest"\nexport declare const manifest: Manifest\n`,
)
write(
  join(dist, "routes.json"),
  JSON.stringify([...output.pages.keys()].sort(), null, 1),
)

// Files the site serves as they are.
const site = join(dist, "site")
write(join(site, "search-index.json"), JSON.stringify(output.search))
write(join(site, "llms.txt"), output.llms)
write(join(site, "sitemap.xml"), output.sitemap)
write(
  join(site, "robots.txt"),
  "User-agent: *\nAllow: /\n\nSitemap: https://docs.matchbox.markets/sitemap.xml\n",
)
write(join(site, "_redirects"), redirectsFile())
write(join(site, "developer", "openapi.json"), reference.document)
for (const [path, markdown] of output.markdownTwins) {
  write(join(site, `${path === "/" ? "/index" : path}.md`), markdown)
}

const report = {
  published: output.pages.size,
  stubs: output.stubs,
  bySection: output.manifest.counts,
}
write(join(dist, "report.json"), JSON.stringify(report, null, 1))
console.log(
  `docs: ${output.pages.size} pages, ${output.stubs.length} stubs held back, ${output.search.entries.length} search entries`,
)
